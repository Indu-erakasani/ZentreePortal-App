class NotificationJourneyTaskSet(TaskSet):
    """
    Simulates a realistic user session:
      1. List notifications
      2. Create one
      3. Mark it read
      4. List again
      5. Occasionally delete or mark-all-read
    """

    def on_start(self):
        self._last_nid = None

    @task(4)
    def list_notifications(self):
        if not hasattr(self.user, 'auth_headers'):
            return
        self.client.get(
            "/api/notifications/",
            headers=self.user.auth_headers,
            name="GET /api/notifications/ [journey]",
        )

    @task(3)
    def create_and_read(self):
        nid = _create_notification(self.client, self.user.auth_headers,
                                   payload={
                                       "type":  random.choice(["new_candidate", "system", "warning"]),
                                       "title": f"Journey notif {random.randint(1, 9999)}",
                                   })
        if nid:
            self._last_nid = nid
            self.client.put(
                f"/api/notifications/{nid}/read",
                headers=self.user.auth_headers,
                name="PUT /api/notifications/<id>/read [journey]",
            )

    @task(1)
    def mark_all_read(self):
        self.client.put(
            "/api/notifications/read-all",
            headers=self.user.auth_headers,
            name="PUT /api/notifications/read-all [journey]",
        )

    @task(1)
    def delete_last(self):
        if self._last_nid:
            self.client.delete(
                f"/api/notifications/{self._last_nid}",
                headers=self.user.auth_headers,
                name="DELETE /api/notifications/<id> [journey]",
            )
            self._last_nid = None


