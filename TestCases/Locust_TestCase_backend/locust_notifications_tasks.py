def _random_email(prefix="locust"):
    suffix = "".join(random.choices(string.ascii_lowercase + string.digits, k=8))
    return f"{prefix}_{suffix}@loadtest.com"


def _register_and_login(client, role="recruiter"):
    """Register a fresh user and return a Bearer auth header dict."""
    email = _random_email(role)
    client.post(
        "/api/auth/register",
        json={
            "first_name": "Load",
            "last_name":  "Tester",
            "email":      email,
            "password":   "Test@1234",
            "role":       role,
        },
        name="/api/auth/register [setup]",
    )
    res = client.post(
        "/api/auth/login",
        json={"email": email, "password": "Test@1234"},
        name="/api/auth/login [setup]",
    )
    token = res.json().get("access_token", "")
    return {"Authorization": f"Bearer {token}"}


def _create_notification(client, headers, payload=None):
    payload = payload or {
        "type":    "new_candidate",
        "title":   "Load-test Notification",
        "message": "Generated by Locust",
    }
    res = client.post(
        "/api/notifications/",
        json=payload,
        headers=headers,
        name="POST /api/notifications/",
    )
    if res.status_code == 201:
        return res.json().get("data", {}).get("_id")
    return None


